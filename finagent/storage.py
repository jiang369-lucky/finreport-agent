from contextlib import contextmanager
from datetime import datetime, timezone
import json
import uuid

import psycopg
from psycopg import sql
from psycopg.rows import dict_row

from .config import settings


def now() -> str:
    return datetime.now(timezone.utc).isoformat()


def uid() -> str:
    return uuid.uuid4().hex


# Keep existing ISO date strings and JSON text so migration preserves every value.
SCHEMA = """
CREATE TABLE IF NOT EXISTS documents(
 id TEXT PRIMARY KEY, company TEXT NOT NULL, code TEXT NOT NULL, title TEXT NOT NULL,
 period TEXT NOT NULL, published TEXT NOT NULL, url TEXT NOT NULL, sha256 TEXT NOT NULL,
 path TEXT NOT NULL, page_count INTEGER NOT NULL, imported_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS pages(
 document_id TEXT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
 page INTEGER NOT NULL, text TEXT NOT NULL, PRIMARY KEY(document_id,page)
);
CREATE TABLE IF NOT EXISTS chunks(
 id TEXT PRIMARY KEY, document_id TEXT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
 page INTEGER NOT NULL, ordinal INTEGER NOT NULL, text TEXT NOT NULL, tokens TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS metrics(
 id TEXT PRIMARY KEY, document_id TEXT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
 page INTEGER NOT NULL, label TEXT NOT NULL, period TEXT NOT NULL, value TEXT NOT NULL,
 unit TEXT NOT NULL, excerpt TEXT NOT NULL, confidence TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions(
 id TEXT PRIMARY KEY, title TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS turns(
 id TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
 question TEXT NOT NULL, answer TEXT NOT NULL DEFAULT '', as_of TEXT NOT NULL,
 status TEXT NOT NULL, created_at TEXT NOT NULL, payload TEXT NOT NULL DEFAULT '{}',
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE IF NOT EXISTS summaries(
 session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE, as_of TEXT NOT NULL,
 through_turn TEXT NOT NULL, content TEXT NOT NULL, created_at TEXT NOT NULL,
 PRIMARY KEY(session_id,as_of)
);
CREATE TABLE IF NOT EXISTS runs(
 id TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
 as_of TEXT NOT NULL, mode TEXT NOT NULL, status TEXT NOT NULL, created_at TEXT NOT NULL,
 ended_at TEXT, latency_ms INTEGER, usage TEXT NOT NULL DEFAULT '{}',
 events TEXT NOT NULL DEFAULT '[]', answer TEXT NOT NULL DEFAULT '',
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE IF NOT EXISTS artifacts(
 id TEXT PRIMARY KEY, session_id TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
 run_id TEXT NOT NULL, tool TEXT NOT NULL, as_of TEXT NOT NULL, payload TEXT NOT NULL,
 created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_document_filter ON documents(company,period,published);
CREATE INDEX IF NOT EXISTS ix_chunk_document_page ON chunks(document_id,page);
CREATE INDEX IF NOT EXISTS ix_metric_lookup ON metrics(label,period,document_id);
CREATE INDEX IF NOT EXISTS ix_turn_session_seq ON turns(session_id,seq);
CREATE INDEX IF NOT EXISTS ix_run_session_seq ON runs(session_id,seq);
CREATE INDEX IF NOT EXISTS ix_artifact_session ON artifacts(session_id,as_of);
"""


@contextmanager
def connect():
    settings.validate_database()
    with psycopg.connect(settings.database_url, row_factory=dict_row, connect_timeout=10) as conn:
        conn.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(settings.database_schema)))
        yield conn


def init_db() -> None:
    settings.validate_database()
    with psycopg.connect(settings.database_url, connect_timeout=10) as conn:
        conn.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(settings.database_schema)))
        conn.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(settings.database_schema)))
        conn.execute(SCHEMA)


def dump(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
